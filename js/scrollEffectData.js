function scrollEffectAssetPath(phase, variant, layer, frameIndex) {
  const base = SCROLL_EFFECT.assetBase;
  if (phase === 'try' || phase === 'fail') {
    if (layer.startsWith('summaryIcon/')) {
      const slot = layer.split('/')[1];
      return `${base}/${phase}/summaryIcon/${slot}/scroll.${phase}.summaryIcon.${slot}.${frameIndex}.png`;
    }
    if (layer === 'textScreen') {
      return `${base}/${phase}/textScreen/scroll.${phase}.textScreen.${frameIndex}.png`;
    }
    const part = layer.replace('itemIcon/', '');
    return `${base}/${phase}/itemIcon/${part}/scroll.${phase}.itemIcon.${part}.${frameIndex}.png`;
  }
  if (phase === 'success') {
    const v = variant ?? 0;
    if (layer.startsWith('summaryIcon/')) {
      const slot = layer.split('/')[1];
      return `${base}/success/${v}/summaryIcon/${slot}/scroll.success.${v}.summaryIcon.${slot}.${frameIndex}.png`;
    }
    if (layer === 'textScreen') {
      return `${base}/success/${v}/textScreen/scroll.success.${v}.textScreen.${frameIndex}.png`;
    }
    const part = layer.replace('itemIcon/', '');
    return `${base}/success/${v}/itemIcon/${part}/scroll.success.${v}.itemIcon.${part}.${frameIndex}.png`;
  }
  return '';
}
